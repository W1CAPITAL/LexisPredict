-- Registros fundamentados em ato judicial, separados de prazos e retornos.
-- Nenhum acesso direto por cliente: somente endpoints autenticados com filtro de empresa.
CREATE TABLE IF NOT EXISTS public.audiencias_monitoradas (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 empresa_id uuid NOT NULL,
 processo_id bigint NOT NULL REFERENCES public.processos(id) ON DELETE CASCADE,
 chave text NOT NULL,
 protocolo_ref text NOT NULL,
 cliente text,
 advogado text,
 tribunal text,
 tipo text NOT NULL CHECK (tipo IN ('conciliacao','instrucao','julgamento','sessao_virtual','audiencia')),
 data_evento date,
 data_fim date,
 hora_local text,
 hora_fim text,
 fuso text,
 modalidade text NOT NULL DEFAULT 'nao_informada' CHECK (modalidade IN ('virtual','presencial','nao_informada')),
 situacao text NOT NULL CHECK (situacao IN ('publicada','data_pendente','cancelada')),
 fonte text NOT NULL CHECK (fonte IN ('DJEN','DataJud')),
 fonte_url text,
 portal_url text,
 evidencia text NOT NULL,
 verificado_em timestamptz NOT NULL DEFAULT now(),
 atualizado_em timestamptz NOT NULL DEFAULT now(),
 CONSTRAINT audiencias_monitoradas_dedupe UNIQUE (empresa_id,processo_id,chave)
);
ALTER TABLE public.audiencias_monitoradas ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.audiencias_monitoradas FROM anon,authenticated;
GRANT SELECT,INSERT,UPDATE,DELETE ON TABLE public.audiencias_monitoradas TO service_role;
GRANT USAGE,SELECT ON SEQUENCE public.audiencias_monitoradas_id_seq TO service_role;
CREATE INDEX IF NOT EXISTS idx_audiencias_empresa_data ON public.audiencias_monitoradas(empresa_id,data_evento);
CREATE INDEX IF NOT EXISTS idx_audiencias_empresa_fim ON public.audiencias_monitoradas(empresa_id,data_fim) WHERE data_fim IS NOT NULL;
COMMENT ON TABLE public.audiencias_monitoradas IS 'Datas oficiais de audiência e sessão; serviço autenticado por empresa; portais de tribunal não são APIs REST.';