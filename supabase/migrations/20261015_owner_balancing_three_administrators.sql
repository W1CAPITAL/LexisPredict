-- Equilíbrio operacional da carteira: 2643 / 3 = 881 cada.
-- created_by é o campo de DONO DA CARTEIRA no LexisPredict.
-- Preserva o valor anterior e nunca altera atendido_por, advogado ou auditoria.
CREATE TABLE IF NOT EXISTS public.lexis_owner_rebalance_audit (
 id bigint generated by default as identity primary key,
 empresa_id uuid not null,
 processo_id bigint not null,
 previous_owner uuid,
 next_owner uuid not null,
 reason text not null,
 recorded_at timestamptz not null default now(),
 batch_id text not null
);
ALTER TABLE public.lexis_owner_rebalance_audit ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.lexis_owner_rebalance_audit FROM PUBLIC, anon,authenticated;
GRANT SELECT,INSERT ON public.lexis_owner_rebalance_audit TO service_role;
GRANT USAGE,SELECT ON SEQUENCE public.lexis_owner_rebalance_audit_id_seq TO service_role;
CREATE INDEX IF NOT EXISTS idx_lexis_owner_rebalance_tenant ON public.lexis_owner_rebalance_audit(empresa_id,recorded_at DESC);

DO $check$
DECLARE davi int;adriana int;kris int;total int;
BEGIN
 SELECT count(*) INTO total FROM public.processos WHERE empresa_id='d37fd4bb-1c71-4dca-b97e-292355918d39';
 SELECT count(*) INTO davi FROM public.processos
 WHERE empresa_id='d37fd4bb-1c71-4dca-b97e-292355918d39' AND created_by IN('88913c7d-8c82-4126-bfd6-0e79039b1fe2','4581d2fe-c358-45f9-a1bd-f90f93dce0fc');
 SELECT count(*) INTO adriana FROM public.processos
 WHERE empresa_id='d37fd4bb-1c71-4dca-b97e-292355918d39' AND created_by IN('b26775a9-6f4a-4191-a188-fec159e860b6','d269f309-a461-4f01-b894-d3a7b54a4b7c');
 SELECT count(*) INTO kris FROM public.processos
 WHERE empresa_id='d37fd4bb-1c71-4dca-b97e-292355918d39' AND created_by IN('14c80ba6-aa63-4682-bb29-90309f0060e9','e72a59fd-d85f-4b4d-bbe1-1966249a14cf');
 IF total<>2643 OR davi<>902 OR adriana<>873 OR kris<>868 THEN
  RAISE EXCEPTION 'O estado da carteira mudou antes da redistribuição: total %, Davi %, Adriana %, Kris %',total,davi,adriana,kris;
 END IF;
END $check$;

WITH
 davi_open AS (
  SELECT id,created_by, row_number() OVER(ORDER BY proximo_retorno ASC NULLS LAST,id) rn
  FROM public.processos
  WHERE empresa_id='d37fd4bb-1c71-4dca-b97e-292355918d39' AND created_by IN('88913c7d-8c82-4126-bfd6-0e79039b1fe2','4581d2fe-c358-45f9-a1bd-f90f93dce0fc')
   AND status IS DISTINCT FROM 'Encerrado' AND status_interno IS DISTINCT FROM 'ENCERRADO'
 ),
 kris_open AS (
  SELECT id,created_by,row_number() OVER(ORDER BY proximo_retorno ASC NULLS LAST,id) rn
  FROM public.processos
  WHERE empresa_id='d37fd4bb-1c71-4dca-b97e-292355918d39' AND created_by IN('14c80ba6-aa63-4682-bb29-90309f0060e9','e72a59fd-d85f-4b4d-bbe1-1966249a14cf')
   AND status IS DISTINCT FROM 'Encerrado' AND status_interno IS DISTINCT FROM 'ENCERRADO'
 ),
 davi_closed AS (
  SELECT id,created_by,row_number() OVER(ORDER BY id) rn
  FROM public.processos
  WHERE empresa_id='d37fd4bb-1c71-4dca-b97e-292355918d39' AND created_by IN('88913c7d-8c82-4126-bfd6-0e79039b1fe2','4581d2fe-c358-45f9-a1bd-f90f93dce0fc')
   AND (status='Encerrado' OR status_interno='ENCERRADO')
 ),
 moves AS (
  SELECT id,created_by previous_owner,'d269f309-a461-4f01-b894-d3a7b54a4b7c'::uuid next_owner FROM davi_open WHERE rn<=7
  UNION ALL
  SELECT id,created_by previous_owner,'4581d2fe-c358-45f9-a1bd-f90f93dce0fc'::uuid next_owner FROM kris_open WHERE rn<=1
  UNION ALL
  SELECT id,created_by previous_owner,'d269f309-a461-4f01-b894-d3a7b54a4b7c'::uuid next_owner FROM davi_closed WHERE rn=1
  UNION ALL
  SELECT id,created_by previous_owner,'e72a59fd-d85f-4b4d-bbe1-1966249a14cf'::uuid next_owner FROM davi_closed WHERE rn BETWEEN 2 AND 15
 ),
 updated AS (
  UPDATE public.processos p
  SET created_by=m.next_owner,
      dados=jsonb_set(
        jsonb_set(
          jsonb_set(coalesce(p.dados,'{}'::jsonb),
            '{original_created_by}',coalesce(p.dados->'original_created_by',to_jsonb(p.created_by::text)),true),
          '{created_by}',to_jsonb(m.next_owner::text),true),
        '{owner_rebalance_2026_10_15}',
        jsonb_build_object('previous_owner',m.previous_owner,'next_owner',m.next_owner,'at',now(),
          'reason','redistribuicao solicitada pelo titular da carteira','batch','lexis-owner-20261015-01'),true),
      updated_at=now()
  FROM moves m WHERE p.id=m.id AND p.empresa_id='d37fd4bb-1c71-4dca-b97e-292355918d39' AND p.created_by=m.previous_owner
  RETURNING p.id, p.empresa_id
 )
INSERT INTO public.lexis_owner_rebalance_audit
 (empresa_id,processo_id,previous_owner,next_owner,reason,batch_id)
SELECT u.empresa_id,u.id,m.previous_owner,m.next_owner,
 'redistribuicao operacional equilibrada - preserva histórico de atendimento e representação',
 'lexis-owner-20261015-01'
FROM updated u JOIN moves m ON m.id=u.id;
